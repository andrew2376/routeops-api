CREATE TABLE vehiculos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    placa VARCHAR(10) NOT NULL UNIQUE,
    marca VARCHAR(60) NOT NULL,
    modelo VARCHAR(80) NOT NULL,
    anio INTEGER NOT NULL,
    tipo VARCHAR(40) NOT NULL,

    capacidad NUMERIC(10, 2),
    kilometraje BIGINT NOT NULL DEFAULT 0,

    numero_soat VARCHAR(50),
    fecha_vencimiento_soat DATE,

    numero_tecnomecanica VARCHAR(50),
    fecha_vencimiento_tecnomecanica DATE,

    estado VARCHAR(30) NOT NULL DEFAULT 'DISPONIBLE',
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_vehiculos_estado
        CHECK (estado IN (
            'DISPONIBLE',
            'EN_RUTA',
            'EN_MANTENIMIENTO',
            'INACTIVO'
        )),

    CONSTRAINT chk_vehiculos_anio
        CHECK (anio BETWEEN 1950 AND 2100),

    CONSTRAINT chk_vehiculos_kilometraje
        CHECK (kilometraje >= 0),

    CONSTRAINT chk_vehiculos_capacidad
        CHECK (capacidad IS NULL OR capacidad > 0)
);